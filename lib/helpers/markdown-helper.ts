import { InvestigationReport } from "../schemas/report-schema";

export function generateReportMarkdown(report: InvestigationReport): string {
  const dateFormatted = new Date(report.createdAt).toLocaleDateString("en-US", {
    month: "long",
    day: "numeric",
    year: "numeric",
  });

  const metadataLines: string[] = [
    `- Source URL: ${report.url}`,
    `- Domain: ${report.domain}`,
    `- Date of Investigation: ${dateFormatted}`,
  ];

  if (report.author) {
    metadataLines.push(`- Author: ${report.author}`);
  }
  if (report.publishDate) {
    metadataLines.push(`- Published: ${report.publishDate}`);
  }

  metadataLines.push(
    `- Claims Analyzed: ${report.claimsCount}`,
    `- Summary: ${report.stats.supported} supported, ${report.stats.misleading} misleading, ${report.stats.needsContext} needs context`
  );

  const lines: string[] = [
    `# Investigation Report: ${report.title}`,
    "",
    ...metadataLines,
    "",
    "## Overall Read",
    "",
    report.overallRead,
    "",
    "## Claims and Evidence",
    "",
  ];

  for (const claim of report.claims) {
    const verdictLabel =
      claim.verdict === "supported"
        ? "Supported"
        : claim.verdict === "misleading"
          ? "Misleading"
          : "Needs Context";

    lines.push(`### Claim ${claim.number}: ${claim.statement}`);
    lines.push("");
    lines.push(`- Verdict: **${verdictLabel}** (Confidence: ${claim.confidence}%)`);
    lines.push(`- Quote from article: "${claim.quote}"`);
    lines.push("");
    lines.push(claim.explanation);
    lines.push("");
    lines.push("#### Evidence and Citations");
    lines.push("");

    if (claim.citations.length === 0) {
      lines.push("_No direct external corroboration found._");
    } else {
      for (const cit of claim.citations) {
        lines.push(`- **[${cit.name}](${cit.url})**: ${cit.snippet}`);
      }
    }
    lines.push("");
  }

  lines.push("---");
  lines.push("_Generated by Jaanch Investigation Engine._");

  return lines.join("\n");
}

export function downloadMarkdownFile(filename: string, content: string): void {
  const blob = new Blob([content], { type: "text/markdown;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
